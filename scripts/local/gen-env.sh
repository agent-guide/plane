#!/bin/bash
# 生成/补齐本地栈全部环境文件（幂等）：
#   scripts/local/.env            —— 本套件运行时凭据（已存在则不动）
#   apps/api/.env                 —— Plane API（确定性重写：example 基底+生成段，保留 SECRET_KEY）
#   $AGWMNGR_DIR/.env.local       —— 管理端（已存在则不动）
#   $GATEWAY_DIR/Caddyfile.local  —— 网关（bcrypt 哈希由口令现算）
# 凭据纪律：口令可读、令牌随机；生成一次落盘，之后 up.sh 幂等复用。
set -euo pipefail
cd "$(dirname "$0")"
[ -f .env ] || { [ -f env.example ] || { echo "missing env.example"; exit 1; }; cp env.example .env; echo "created scripts/local/.env"; }
set -a; source .env; set +a
LOCAL_DIR="$(pwd)"

step()  { printf "\n\033[1m== %s ==\033[0m\n" "$*"; }
ok()    { printf "  \033[32m[OK]\033[0m %s\n" "$*"; }
warn()  { printf "  \033[33m[WARN]\033[0m %s\n" "$*"; }
API_DIR="$LOCAL_DIR/../../apps/api"
MGR_DIR="${MGR_DIR:-${AGWMNGR_DIR:-$HOME/Desktop/shu/agwmngr}}"
GW_DIR="${GATEWAY_DIR:-$HOME/Desktop/shu/agent-gateway}"

step "1. Plane API env (apps/api/.env)"
if [ -f "$API_DIR/.env" ]; then
  SECRET_KEY="$(grep '^SECRET_KEY=' "$API_DIR/.env" | head -1 | cut -d= -f2- | tr -d '"')"
else SECRET_KEY="$(python3 -c 'import secrets;print(secrets.token_urlsafe(50))')"; fi
[ -n "$SECRET_KEY" ] || SECRET_KEY="$(python3 -c 'import secrets;print(secrets.token_urlsafe(50))')"
ORCH_TOKEN="${ORCH_TOKEN:-$(openssl rand -hex 24)}"
TENANT_TOKEN="${TENANT_TOKEN:-}"
{
  cat "$API_DIR/.env.example"
  # 保活既有运行时凭据（Airflow token 每次 up.sh 重签，这里只做无损搬运——
  # 曾因写空值把运行中栈的 token 抹掉，2026-11-17 实证）
  if [ -f "$API_DIR/.env" ]; then
    grep -E '^ORCHESTRATION_AIRFLOW_TOKEN=.+' "$API_DIR/.env" || true
  fi
  cat <<EOF
SECRET_KEY="$SECRET_KEY"
POSTGRES_HOST=127.0.0.1
POSTGRES_PORT=$PG_PORT
POSTGRES_USER="${POSTGRES_USER:-plane}"
POSTGRES_PASSWORD="${POSTGRES_PASSWORD:-plane}"
POSTGRES_DB="${POSTGRES_DB:-plane}"
DATABASE_URL="${DATABASE_URL:-postgresql://plane:plane@127.0.0.1:$PG_PORT/plane}"
REDIS_HOST=127.0.0.1
REDIS_PORT=$REDIS_PORT
REDIS_URL=redis://127.0.0.1:$REDIS_PORT/
AMQP_URL=redis://127.0.0.1:$REDIS_PORT/1
AWS_REGION=us-east-1
AWS_ACCESS_KEY_ID=plane
AWS_SECRET_ACCESS_KEY=plane12345
AWS_S3_ENDPOINT_URL=http://127.0.0.1:9000
AWS_S3_BUCKET_NAME=uploads
USE_MINIO=0
AGWMNGR_BASE_URL=http://127.0.0.1:$MGR_PORT
ORCHESTRATION_INTERNAL_BASE_URL=http://127.0.0.1:$API_PORT
ORCHESTRATION_INTERNAL_TOKEN=$ORCH_TOKEN
ORCHESTRATION_AIRFLOW_BASE_URL=http://127.0.0.1:$AIRFLOW_PORT
ORCHESTRATION_DAG_ROOT="${ORCHESTRATION_DAG_ROOT:-/tmp/agent-team-dags}"
EOF
  [ -n "$TENANT_TOKEN" ] && printf 'AGWMNGR_TENANT_TOKEN=%s\nAGWMNGR_TENANT_ID=%s\n' "$TENANT_TOKEN" "$TENANT_ID"
} > "$API_DIR/.env.new" && mv "$API_DIR/.env.new" "$API_DIR/.env"
grep -q '^ORCH_TOKEN=' .env || echo "ORCH_TOKEN=$ORCH_TOKEN" >> .env
ok "apps/api/.env rewritten (api :$API_PORT / agwmngr :$MGR_PORT / airflow :$AIRFLOW_PORT)"
# Plane web env：后端地址指向 api（web 探不到后端会显示「didn't start up correctly」）
WEB_ENV="$LOCAL_DIR/../../apps/web/.env"
[ -f "$WEB_ENV" ] || cp "$LOCAL_DIR/../../apps/web/.env.example" "$WEB_ENV"
grep -q '^VITE_API_BASE_URL=' "$WEB_ENV" && sed -i '' "s|^VITE_API_BASE_URL=.*|VITE_API_BASE_URL=\"http://localhost:$API_PORT\"|" "$WEB_ENV" \
  || printf 'VITE_API_BASE_URL="http://localhost:%s"\n' "$API_PORT" >> "$WEB_ENV"
ok "apps/web/.env 指向 api :$API_PORT"

step "2. agwmngr env ($MGR_DIR/.env.local)"
if [ ! -f "$MGR_DIR/.env.local" ]; then
  MGR_SECRET="$(openssl rand -hex 32)"
  MGR_HASH="$(cd "$MGR_DIR" && bun -e "import b from 'bcryptjs'; console.log(b.hashSync('$MGR_ADMIN_PASSWORD', 12))")"
  { echo "MANAGER_SECRET_KEY=$MGR_SECRET"
    echo "MANAGER_DB_PATH=data/manager.db"
    echo "AGWMNGR_ADMIN_USER=$MGR_ADMIN_USER"
    echo "AGWMNGR_ADMIN_PASSWORD_HASH='$MGR_HASH'"; } > "$MGR_DIR/.env.local"
  ok "created"; else ok "exists, kept"; fi

step "3. gateway Caddyfile ($GW_DIR/Caddyfile.local)"
GW_HASH="${GW_HASH:-}"
if [ -z "$GW_HASH" ]; then
  GW_HASH="$(cd "$MGR_DIR" && bun -e "import b from 'bcryptjs'; console.log(b.hashSync('$GW_ADMIN_PASSWORD', 12))")"
  echo "GW_HASH='$GW_HASH'" >> .env
fi
cat > "$GW_DIR/Caddyfile.local" <<EOF
# generated by scripts/local/gen-env.sh - sites bind both localhost and 127.0.0.1
# (Host-mismatch returns empty 200 - the false-alive trap, 2026-11-16)
{
	admin localhost:$GW_CADDY_ADMIN_PORT
	log {
		output stderr
		format console
		level INFO
	}
	agent_gateway {
		config_store sqlite {
			path ./data/configstore.db
		}
		metrics {
			retention_days 30
		}
	}
}

http://localhost:$GW_ADMIN_PORT, http://127.0.0.1:$GW_ADMIN_PORT {
	route /admin/* {
		@needauth {
			not path /admin/health
			not method OPTIONS
		}
		basic_auth @needauth {
			$GW_ADMIN_USER $GW_HASH
		}
		agent_gateway_admin
	}
}

http://localhost:$GW_DATA_PORT, http://127.0.0.1:$GW_DATA_PORT {
	log {
		output stderr
		format console
		level INFO
	}
	agent_route_dispatcher {
		llm_api openai
		llm_api anthropic
		llm_api cc
		mcp
		agent
	}
}
EOF
ok "gateway Caddyfile.local written (basic user $GW_ADMIN_USER; password in scripts/local/.env)"

grep -q '__SET_ME__' .env && warn "LLM_API_KEY still placeholder - provision.sh will skip model chain"
echo; echo "done. next: bash scripts/local/up.sh"
